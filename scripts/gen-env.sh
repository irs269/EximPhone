#!/bin/sh
# Generates a production .env with fresh random secrets (never reuse .env.example values).
# Usage: sh scripts/gen-env.sh <public-ip> [ldap-url] [ldap-base-dn] [ldap-bind-dn]
#   public-ip    address clients use to reach the server (media, TURN, SIP, provisioning)
#   ldap-*       Active Directory settings; the LDAP bind password is asked on the terminal.
# Writes .env (mode 600). Refuses to overwrite an existing file.
set -eu
cd "$(dirname "$0")/.."
[ -e .env ] && { echo ".env already exists: move it away first" >&2; exit 1; }
PUBLIC_IP="${1:?usage: gen-env.sh <public-ip> [ldap-url] [ldap-base-dn] [ldap-bind-dn]}"
LDAP_URL="${2:-ldaps://ad.exim.local:636}"
LDAP_BASE_DN="${3:-OU=Users,DC=exim,DC=local}"
LDAP_BIND_DN="${4:-CN=svc-eximphone,OU=Service,DC=exim,DC=local}"

hex() { openssl rand -hex "$1"; }
printf 'LDAP bind password for %s: ' "$LDAP_BIND_DN" >&2
stty -echo 2>/dev/null || true; read -r LDAP_BIND_PASSWORD; stty echo 2>/dev/null || true; echo >&2

umask 077
cat > .env <<EOF
# Generated by scripts/gen-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file private (mode 600).
# Back up MESSAGE_KEY, RECORDING_KEY, SIP_KEY and BACKUP_PASSPHRASE OUTSIDE the server: without them
# messages, recordings, phone secrets and backups cannot be read.
POSTGRES_USER=eximphone
POSTGRES_PASSWORD=$(hex 24)
POSTGRES_DB=eximphone
REDIS_PASSWORD=$(hex 24)
S3_ACCESS_KEY_ID=GK$(hex 12)
S3_SECRET_ACCESS_KEY=$(hex 32)
GARAGE_RPC_SECRET=$(hex 32)
JWT_SECRET=$(hex 32)
INTERNAL_TOKEN=$(hex 24)
TURN_SECRET=$(hex 24)
MESSAGE_KEY=$(hex 32)
RECORDING_KEY=$(hex 32)
SIP_KEY=$(hex 32)
BACKUP_PASSPHRASE=$(hex 24)
RECORDING_RETENTION_DAYS=365
LOG_LEVEL=info
PUBLIC_IP=$PUBLIC_IP
SIP_DOMAIN=eximphone.exim.local
SIP_REQUIRE_TLS=true
SIP_REQUIRE_SRTP=true
# Active Directory (read-only service account)
LDAP_URL=$LDAP_URL
LDAP_BASE_DN=$LDAP_BASE_DN
LDAP_USER_ATTR=sAMAccountName
LDAP_BIND_DN=$LDAP_BIND_DN
LDAP_BIND_PASSWORD=$LDAP_BIND_PASSWORD
# First administrators (usernames). Remove this line once roles are assigned in the application.
INITIAL_IT_ADMINS=
EOF
chmod 600 .env
echo ".env written. Next steps:" >&2
echo "  1. put the TLS certificate and key in nginx/certs/server.crt and server.key (readable by the services)" >&2
echo "  2. set INITIAL_IT_ADMINS, then: docker compose -f docker-compose.yml -f docker-compose.prod.yml up -d --build --wait" >&2
echo "  3. replace the development IP ranges of the sites (PUT /api/admin/sites/{id}); see docs/deployment.md" >&2
